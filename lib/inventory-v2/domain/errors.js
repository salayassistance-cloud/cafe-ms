export class InventoryV2DomainError extends Error {
  constructor(code, message, details = {}) {
    super(message || code);
    this.name = "InventoryV2DomainError";
    this.code = code;
    this.details = Object.freeze({ ...details });
  }
}

export function domainError(code, message, details) {
  return new InventoryV2DomainError(code, message, details);
}

export function fail(code, message, details) {
  throw domainError(code, message, details);
}

export function isDomainError(error, code) {
  return (
    error instanceof InventoryV2DomainError &&
    (code === undefined || error.code === code)
  );
}

export default InventoryV2DomainError;
