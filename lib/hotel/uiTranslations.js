export function translateHotel(lang, key, vars, fallback) {
  const dictionary = HOTEL_UI_TRANSLATIONS[lang] || HOTEL_UI_TRANSLATIONS.en;
  const template =
    dictionary[key] ??
    HOTEL_UI_TRANSLATIONS.en[key] ??
    fallback ??
    key;
  if (!vars) return template;
  return String(template).replace(/\{(\w+)\}/g, (match, name) =>
    vars[name] === undefined || vars[name] === null ? match : String(vars[name])
  );
}
